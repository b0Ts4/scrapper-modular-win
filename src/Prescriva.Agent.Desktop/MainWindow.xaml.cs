    private void ApplyWindowFilter()
    {
        var query = OpenWindowsSearchBox.Text;
        var visible = OpenWindowFilter.Apply(_openWindows.Select(item => item.Info), query)
            .Select(info => _openWindows.First(item => item.Info == info))
            .ToList();
        OpenWindowsList.ItemsSource = visible;
        OpenWindowsEmptyText.Text = _openWindows.Count == 0
            ? "Nenhum programa aberto encontrado. Abra o programa que você quer integrar e clique em 'Atualizar lista'."
            : $"Nenhum programa corresponde a '{query.Trim()}'. Apague a busca ou tente outra palavra.";
        OpenWindowsEmptyText.Visibility = visible.Count == 0 ? Visibility.Visible : Visibility.Collapsed;
        UseSelectedWindowButton.IsEnabled = OpenWindowsList.SelectedItem is not null;
    }

