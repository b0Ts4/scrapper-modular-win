    /// <summary>Redraws the field, button and checkbox lists when the configuration changed.</summary>
    private void RefreshWizardLists()
    {
        var configuration = _editorViewModel?.Configuration;
        if (ReferenceEquals(configuration, _listedConfiguration) && configuration is not null)
        {
            return;
        }

        _listedConfiguration = configuration;
        var fields = configuration?.Fields ?? [];
        var triggers = configuration?.Triggers ?? [];

        FieldsList.ItemsSource = fields.Select(field => new FieldItem(field)).ToList();
        FieldsEmptyText.Visibility = fields.Length == 0 ? Visibility.Visible : Visibility.Collapsed;

        var names = fields.ToDictionary(field => field.Id, field => field.Meaning, StringComparer.Ordinal);
        TriggersList.ItemsSource = triggers.Select(trigger => new TriggerItem(trigger, names)).ToList();
        TriggersEmptyText.Visibility = triggers.Length == 0 ? Visibility.Visible : Visibility.Collapsed;

        var wasChecked = _captureChoices.Where(choice => choice.IsChecked).Select(choice => choice.Id).ToHashSet(StringComparer.Ordinal);
        _captureChoices = fields.Select(field => new CaptureFieldChoice(field.Id, field.Meaning, wasChecked.Contains(field.Id))).ToList();
        CaptureFieldsList.ItemsSource = _captureChoices;
        CaptureFieldsEmptyText.Visibility = fields.Length == 0 ? Visibility.Visible : Visibility.Collapsed;

        var selectedField = ResolveFieldBox.SelectedValue as string;
        ResolveFieldBox.SelectedValuePath = "Field.Id";
        ResolveFieldBox.ItemsSource = fields.Select(field => new FieldItem(field)).ToList();
        ResolveFieldBox.SelectedValue = selectedField is not null && names.ContainsKey(selectedField)
            ? selectedField
            : fields.FirstOrDefault()?.Id;

        CurrentIntegrationText.Text = configuration is null
            ? "Nenhuma integração aberta. Comece pelo passo 1."
            : $"Integração '{configuration.Name}' · programa {configuration.Application.ProcessIdentity} · {fields.Length} campo(s), {triggers.Length} botão(ões)";
    }

